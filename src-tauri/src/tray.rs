//! System tray icon and its native menu.

use tauri::{
    AppHandle, Manager, Wry,
    image::Image,
    include_image,
    menu::{Menu, MenuItem, PredefinedMenuItem},
    tray::{MouseButton, MouseButtonState, TrayIconBuilder, TrayIconEvent},
};

use crate::{i18n, settings::SettingsStore, updates, window};

#[cfg(all(target_os = "linux", target_arch = "aarch64"))]
mod host;

const TRAY_ID: &str = "main";
const MENU_OPEN: &str = "open";
const MENU_QUIT: &str = "quit";

// Other backends initialize synchronously and can return an error.
#[cfg_attr(
    all(target_os = "linux", target_arch = "aarch64"),
    allow(clippy::unnecessary_wraps)
)]
pub fn create(app: &AppHandle) -> tauri::Result<()> {
    #[cfg(all(target_os = "linux", target_arch = "aarch64"))]
    {
        host::create(app);
        Ok(())
    }
    #[cfg(not(all(target_os = "linux", target_arch = "aarch64")))]
    build(app)
}

fn build(app: &AppHandle) -> tauri::Result<()> {
    let builder = TrayIconBuilder::with_id(TRAY_ID)
        .icon(icon(app, false))
        // macOS tints template images for light and dark menu bars; ignored elsewhere.
        .icon_as_template(cfg!(target_os = "macos"))
        .tooltip("NanoPrint")
        .menu(&menu(app)?)
        // AppIndicator only exposes the menu; native SNI also delivers click events.
        .show_menu_on_left_click(false)
        .on_menu_event(|app, event| match event.id.as_ref() {
            MENU_OPEN => window::show_settings(app),
            MENU_QUIT => app.exit(0),
            _ => {}
        })
        .on_tray_icon_event(|tray, event| {
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                window::show_settings(tray.app_handle());
            }
        });
    #[cfg(all(target_os = "linux", target_arch = "aarch64"))]
    let builder = builder.title("NanoPrint");
    builder.build(app)?;
    show_update(app, updates::waiting_for_user(app).as_deref());
    Ok(())
}

/// Shows whether an update waits for the user to install it (see `updates::waiting_for_user`): a
/// dot on the icon and the version in the tooltip.
pub fn show_update(app: &AppHandle, version: Option<&str>) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return;
    };
    let tooltip = version.map_or_else(
        || "NanoPrint".to_owned(),
        |version| {
            let locale = i18n::resolve(app.state::<SettingsStore>().get().language);
            i18n::t(locale, "tray.updateAvailable").replace("{version}", version)
        },
    );
    let result = tray
        .set_icon(Some(icon(app, version.is_some())))
        .and_then(|()| tray.set_icon_as_template(cfg!(target_os = "macos")))
        .and_then(|()| tray.set_tooltip(Some(tooltip)));
    if let Err(err) = result {
        log::warn!("could not update the tray icon: {err}");
    }
}

/// The tray image for this platform, generated by `npm run icons` from `assets/brand`; `badge`
/// adds the dot that marks an update waiting for the user.
#[cfg(target_os = "macos")]
fn icon(_app: &AppHandle, badge: bool) -> Image<'static> {
    if badge {
        include_image!("icons/tray/tray-badge-template@2x.png")
    } else {
        include_image!("icons/tray/tray-template@2x.png")
    }
}

/// The tray image that matches the display scale, so Windows and Linux never resample it.
#[cfg(not(target_os = "macos"))]
fn icon(app: &AppHandle, badge: bool) -> Image<'static> {
    // Tray icons are 16 logical pixels on Windows and 22 on Linux panels.
    let logical = if cfg!(windows) { 16.0 } else { 22.0 };
    let scale = app
        .primary_monitor()
        .ok()
        .flatten()
        .map_or(1.0, |monitor| monitor.scale_factor());
    // Clamped to the generated sizes (16–48 px), so the cast cannot truncate or lose the sign.
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let pixels = (logical * scale).round().clamp(16.0, 48.0) as u32;
    match (pixels, badge) {
        (..=16, false) => include_image!("icons/tray/tray-16.png"),
        (17..=20, false) => include_image!("icons/tray/tray-20.png"),
        (21..=22, false) => include_image!("icons/tray/tray-22.png"),
        (23..=24, false) => include_image!("icons/tray/tray-24.png"),
        (25..=32, false) => include_image!("icons/tray/tray-32.png"),
        (33..=40, false) => include_image!("icons/tray/tray-40.png"),
        (_, false) => include_image!("icons/tray/tray-48.png"),
        (..=16, true) => include_image!("icons/tray/tray-badge-16.png"),
        (17..=20, true) => include_image!("icons/tray/tray-badge-20.png"),
        (21..=22, true) => include_image!("icons/tray/tray-badge-22.png"),
        (23..=24, true) => include_image!("icons/tray/tray-badge-24.png"),
        (25..=32, true) => include_image!("icons/tray/tray-badge-32.png"),
        (33..=40, true) => include_image!("icons/tray/tray-badge-40.png"),
        (_, true) => include_image!("icons/tray/tray-badge-48.png"),
    }
}

/// Rebuilds the menu and the tooltip, e.g. after the language changed.
pub fn refresh(app: &AppHandle) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return;
    };
    let result = menu(app).and_then(|menu| tray.set_menu(Some(menu)));
    if let Err(err) = result {
        log::warn!("could not update the tray menu: {err}");
    }
    show_update(app, updates::waiting_for_user(app).as_deref());
}

fn menu(app: &AppHandle) -> tauri::Result<Menu<Wry>> {
    let locale = i18n::resolve(app.state::<SettingsStore>().get().language);
    let item = |id, key| MenuItem::with_id(app, id, i18n::t(locale, key), true, None::<&str>);
    Menu::with_items(
        app,
        &[
            &item(MENU_OPEN, "tray.open")?,
            &PredefinedMenuItem::separator(app)?,
            &item(MENU_QUIT, "tray.quit")?,
        ],
    )
}
