//! System tray icon and its native menu.

use tauri::{
    AppHandle, Manager, Wry,
    image::Image,
    include_image,
    menu::{Menu, MenuItem, PredefinedMenuItem},
    tray::{MouseButton, MouseButtonState, TrayIconBuilder, TrayIconEvent},
};

use crate::{i18n, settings::SettingsStore, window};

const TRAY_ID: &str = "main";
const MENU_OPEN: &str = "open";
const MENU_QUIT: &str = "quit";

pub fn create(app: &AppHandle) -> tauri::Result<()> {
    TrayIconBuilder::with_id(TRAY_ID)
        .icon(icon(app))
        // macOS tints template images for light and dark menu bars; ignored elsewhere.
        .icon_as_template(cfg!(target_os = "macos"))
        .tooltip("NanoPrint")
        .menu(&menu(app)?)
        // Left click opens the settings window and right click shows the menu. Linux has no tray
        // click events, so there the menu is the only entry point.
        .show_menu_on_left_click(false)
        .on_menu_event(|app, event| match event.id.as_ref() {
            MENU_OPEN => window::show_settings(app),
            MENU_QUIT => app.exit(0),
            _ => {}
        })
        .on_tray_icon_event(|tray, event| {
            if let TrayIconEvent::Click {
                button: MouseButton::Left,
                button_state: MouseButtonState::Up,
                ..
            } = event
            {
                window::show_settings(tray.app_handle());
            }
        })
        .build(app)?;
    Ok(())
}

/// The tray image for this platform, generated by `npm run icons` from `assets/brand`.
#[cfg(target_os = "macos")]
fn icon(_app: &AppHandle) -> Image<'static> {
    include_image!("icons/tray/tray-template@2x.png")
}

/// The tray image that matches the display scale, so Windows and Linux never resample it.
#[cfg(not(target_os = "macos"))]
fn icon(app: &AppHandle) -> Image<'static> {
    // Tray icons are 16 logical pixels on Windows and 22 on Linux panels.
    let logical = if cfg!(windows) { 16.0 } else { 22.0 };
    let scale = app
        .primary_monitor()
        .ok()
        .flatten()
        .map_or(1.0, |monitor| monitor.scale_factor());
    // Clamped to the generated sizes (16–48 px), so the cast cannot truncate or lose the sign.
    #[allow(clippy::cast_possible_truncation, clippy::cast_sign_loss)]
    let pixels = (logical * scale).round().clamp(16.0, 48.0) as u32;
    match pixels {
        ..=16 => include_image!("icons/tray/tray-16.png"),
        17..=20 => include_image!("icons/tray/tray-20.png"),
        21..=22 => include_image!("icons/tray/tray-22.png"),
        23..=24 => include_image!("icons/tray/tray-24.png"),
        25..=32 => include_image!("icons/tray/tray-32.png"),
        33..=40 => include_image!("icons/tray/tray-40.png"),
        _ => include_image!("icons/tray/tray-48.png"),
    }
}

/// Rebuilds the menu, e.g. after the language changed.
pub fn refresh(app: &AppHandle) {
    let Some(tray) = app.tray_by_id(TRAY_ID) else {
        return;
    };
    let result = menu(app).and_then(|menu| tray.set_menu(Some(menu)));
    if let Err(err) = result {
        log::warn!("could not update the tray menu: {err}");
    }
}

fn menu(app: &AppHandle) -> tauri::Result<Menu<Wry>> {
    let locale = i18n::resolve(app.state::<SettingsStore>().get().language);
    let item = |id, key| MenuItem::with_id(app, id, i18n::t(locale, key), true, None::<&str>);
    Menu::with_items(
        app,
        &[
            &item(MENU_OPEN, "tray.open")?,
            &PredefinedMenuItem::separator(app)?,
            &item(MENU_QUIT, "tray.quit")?,
        ],
    )
}
